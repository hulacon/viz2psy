"""Frame captions from a prompted vision-language model (Qwen3-VL-8B-Instruct).

One English sentence per image or video frame, written by an instruction-tuned
VLM from a fixed prompt. It sits beside ``caption`` (BLIP), which keeps its
own name and defaults so earlier outputs keep their provenance.

Everything that shapes the text is frozen and recorded in the sidecar
(``models.caption_vlm.preprocessing``), because a prompted model's output is a
function of its prompt as much as of its weights:

- **weights**: ``Qwen/Qwen3-VL-8B-Instruct`` at a pinned Hub revision
  (``checkpoint`` carries ``<repo>@<revision>``); the sidecar's
  ``model_version`` is the transformers version;
- **prompt**: ``PROMPT`` verbatim, versioned as ``PROMPT_VERSION``. A
  different prompt is a different feature: change ``PROMPT_VERSION`` with it;
- **input size**: the picture is shrunk (never enlarged) to at most
  ``MAX_SIDE`` px on its long side with its aspect kept, then handed to the
  Qwen3-VL processor's default dynamic resolution. Video frames arrive after
  the framing rule's stage 0 (bars cropped, pixels squared), so the
  captioner sees the active picture whole, like every other model;
- **decoding**: greedy, at most ``MAX_NEW_TOKENS`` new tokens, bfloat16.

Batched generation pads on the left; in bfloat16 a frame's caption can differ
in rare tokens with the batch it shares, so runs to be compared should use
the same ``--batch-size``.
"""

from __future__ import annotations

from PIL import Image

from viz2psy.models.base import BaseModel

CHECKPOINT = "Qwen/Qwen3-VL-8B-Instruct"
#: Hub commit of CHECKPOINT the feature is defined on.
REVISION = "0c351dd01ed87e9c1b53cbc748cba10e6187ff3b"
PROMPT_VERSION = "caption-prompt v1"
PROMPT = ("Describe what is happening in this frame from a film in one sentence of about 10-20 words: who or "
          "what is visible and what they are doing. Output only the sentence.")
MAX_SIDE = 768
MAX_NEW_TOKENS = 64
#: Qwen3-VL's model classes first appear in this transformers release.
MIN_TRANSFORMERS = "4.57"
COLUMN = "caption_vlm_text"


def fit_long_side(image: Image.Image, max_side: int = MAX_SIDE) -> Image.Image:
    """A copy at most ``max_side`` px on its long side, aspect kept, never enlarged.

    PIL's ``thumbnail`` (bicubic, reducing_gap 2.0), as the caption bake-off
    that chose this model ran it.
    """
    out = image.convert("RGB")  # always a copy, so thumbnail never edits the caller's frame
    out.thumbnail((max_side, max_side))
    return out


class CaptionVLMModel(BaseModel):
    """One-sentence frame captions from Qwen3-VL-8B-Instruct with a fixed prompt."""

    name = "caption_vlm"
    checkpoint = f"{CHECKPOINT}@{REVISION}"
    # A string column (the sidecar declares dtype "string"; consumers exclude
    # it from numeric spaces). The model is instruction-tuned end to end on
    # image-description data and prompted to describe; nothing is fitted to
    # our stimuli, and there is no similarity-to-prompt step (not zero-shot).
    labels = {
        "default": {
            "interpretability": "nameable",
            "derivation": "trained-on-labels",
            "LongName": "Frame caption (VLM)",
            "Description": f"One-sentence English description generated by {CHECKPOINT} "
                           f"({PROMPT_VERSION}; greedy, <= {MAX_NEW_TOKENS} new tokens)",
        },
        "columns": {},
    }

    def __init__(
        self,
        model_name: str = CHECKPOINT,
        revision: str = REVISION,
        device: str | None = None,
    ):
        super().__init__(device=device)
        self.model_name = model_name
        self.revision = revision
        self.checkpoint = f"{model_name}@{revision}"
        self._processor = None
        self._conv = None

    @staticmethod
    def describe_preprocessing() -> dict:
        """The input transform and generation settings, as recorded in the sidecar."""
        return {
            "resize": f"shrink to <= {MAX_SIDE} px long side, aspect kept, never enlarged "
                      "(PIL thumbnail: bicubic, reducing_gap 2.0)",
            "processor": "Qwen3-VL default image processor (dynamic resolution, aspect kept)",
            "prompt_version": PROMPT_VERSION,
            "prompt": PROMPT,
            "decoding": f"greedy, max_new_tokens {MAX_NEW_TOKENS}, bfloat16, left padding",
        }

    def load(self) -> None:
        import torch
        import transformers
        from packaging.version import Version

        if Version(transformers.__version__) < Version(MIN_TRANSFORMERS):
            raise RuntimeError(f"caption_vlm needs transformers>={MIN_TRANSFORMERS} (Qwen3-VL); "
                               f"found {transformers.__version__}. Upgrade transformers in this env.")
        from transformers import AutoModelForImageTextToText, AutoProcessor

        self._processor = AutoProcessor.from_pretrained(self.model_name, revision=self.revision)
        self._processor.tokenizer.padding_side = "left"
        self.model = (
            AutoModelForImageTextToText.from_pretrained(self.model_name, revision=self.revision,
                                                        dtype=torch.bfloat16)
            .eval()
            .to(self.device)
        )
        self._conv = self._processor.apply_chat_template(
            [{"role": "user", "content": [{"type": "image"}, {"type": "text", "text": PROMPT}]}],
            tokenize=False, add_generation_prompt=True)

    def predict(self, image: Image.Image) -> dict:
        return self.predict_batch([image])[0]

    def predict_batch(self, images: list[Image.Image]) -> list[dict]:
        import torch

        ims = [fit_long_side(img) for img in images]
        enc = self._processor(text=[self._conv] * len(ims), images=ims, padding=True,
                              return_tensors="pt").to(self.device)
        if "pixel_values" in enc:
            enc["pixel_values"] = enc["pixel_values"].to(torch.bfloat16)
        with torch.inference_mode():
            out = self.model.generate(**enc, max_new_tokens=MAX_NEW_TOKENS, do_sample=False)
        return [{COLUMN: c} for c in decode_new_tokens(self._processor.tokenizer, out,
                                                       enc["input_ids"].shape[1])]


def decode_new_tokens(tokenizer, generated, n_prompt: int) -> list[str]:
    """The generated sentence per row: tokens after the (left-padded) prompt.

    An empty caption is an error, never a stored empty string: the prompt asks
    for a sentence, so an empty one means the generation broke.
    """
    caps = [tokenizer.decode(row[n_prompt:], skip_special_tokens=True).strip() for row in generated]
    empty = [i for i, c in enumerate(caps) if not c]
    if empty:
        raise ValueError(f"caption_vlm generated {len(empty)} empty caption(s) in a batch of {len(caps)} "
                         f"(rows {empty[:5]})")
    return caps
